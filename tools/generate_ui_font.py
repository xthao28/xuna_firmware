#!/usr/bin/env python3
"""Generate the device-card fonts (TextRaster UiFont tables) from Be Vietnam Pro.

Glyph set = printable ASCII + every non-ASCII character in the string
literals of lib/xuna_core/include/xuna/visual/DeviceCards.h, so new card text
only needs a re-run. kFontValue also draws free text (the speech bubble,
SpeechBubble.h, Vietnamese and English), so it gets every Vietnamese letter
and the punctuation replies use. Fonts: ../mobile/assets/fonts (OFL-1.1, copy of the
licence in assets/licenses/OFL-BeVietnamPro.txt).
Usage: python tools/generate_ui_font.py [fonts_dir]
"""
from pathlib import Path
import re
import sys
import unicodedata
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / 'mobile/assets/fonts'
SOURCE = ROOT / 'lib/xuna_core/include/xuna/visual/DeviceCards.h'
# name, file, pixel size, free text
SPECS = [('kFontTitle', 'BeVietnamPro-ExtraBold.ttf', 20, False),
         ('kFontValue', 'BeVietnamPro-SemiBold.ttf', 14, True),
         ('kFontLabel', 'BeVietnamPro-Medium.ttf', 11, False)]

text = SOURCE.read_text(encoding='utf-8')
literals = re.findall(r'"((?:[^"\\]|\\.)*)"', text)
chars = {chr(c) for c in range(0x20, 0x7F)}
for lit in literals:
    chars.update(ch for ch in lit if ord(ch) >= 0x80)
codepoints = sorted(ord(c) for c in chars)

# Every Vietnamese letter (12 vowels x 6 tones, both cases, plus đ) and the
# typographic punctuation replies use, precomposed (NFC).
vietnamese = {'đ', 'Đ'}
for vowel in 'aăâeêioôơuưy':
    for tone in ('', '̀', '́', '̉', '̃', '̣'):
        letter = unicodedata.normalize('NFC', vowel + tone)
        vietnamese.update((letter, letter.upper()))
punctuation = set('‘’“”…–—·•°«»')
free_codepoints = sorted(set(codepoints) | {ord(c) for c in vietnamese | punctuation})


def build(name, file, size, free):
    font = ImageFont.truetype(str(FONTS / file), size)
    ascent, descent = font.getmetrics()
    glyphs, alpha = [], []
    for cp in free_codepoints if free else codepoints:
        ch = chr(cp)
        advance = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        offset = len(alpha)
        if w and h:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
            alpha.extend(im.tobytes())
        assert -128 <= x0 < 128 and -128 <= y0 < 128 and w < 256 and h < 256 and advance < 256
        glyphs.append((cp, offset, w, h, x0, y0, advance))
    return glyphs, alpha, ascent, ascent + descent


header = ['// Generated by tools/generate_ui_font.py (Be Vietnam Pro, OFL-1.1).', '#pragma once',
          '#include <xuna/visual/TextRaster.h>', 'namespace xuna { namespace ui {']
body = ['// Generated by tools/generate_ui_font.py (Be Vietnam Pro, OFL-1.1).',
        '#include "assets/XunaUiFont.h"', 'namespace xuna { namespace ui {', 'namespace {']
defs = []
total = 0
for name, file, size, free in SPECS:
    glyphs, alpha, ascent, line = build(name, file, size, free)
    total += len(alpha) + len(glyphs) * 16
    header.append('extern const UiFont %s;  // %s %dpx' % (name, file, size))
    body.append('const UiGlyph %sGlyphs[] = {' % name)
    body += ['  {0x%04x, %d, %d, %d, %d, %d, %d},' % g for g in glyphs]
    body.append('};')
    body.append('const uint8_t %sAlpha[] = {' % name)
    body += ['  ' + ','.join(str(v) for v in alpha[i:i + 32]) + ',' for i in range(0, len(alpha), 32)]
    body.append('};')
    defs.append('const UiFont %s = {%sGlyphs, %d, %sAlpha, %d, %d};' % (name, name, len(glyphs), name, ascent, line))
header += ['}}', '']
body += ['}  // namespace'] + defs + ['}}', '']
(ROOT / 'include/assets/XunaUiFont.h').write_text('\n'.join(header), encoding='utf-8')
(ROOT / 'src/assets/XunaUiFont.cpp').write_text('\n'.join(body), encoding='utf-8')
print('glyphs per font:', len(codepoints), 'free-text font:', len(free_codepoints), 'non-ASCII:', ''.join(c for c in sorted(chars) if ord(c) >= 0x80),
      'flash bytes:', total)
