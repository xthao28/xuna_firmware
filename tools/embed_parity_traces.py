"""Embed the S21 parity traces into a generated header (xuna_parity only)."""
from pathlib import Path

Import("env")
TRACES = ["c3_cut_then_commit", "c8_dayparts", "c9_lifelab_days"]
project = Path(env.subst("$PROJECT_DIR"))
out_dir = Path(env.subst("$BUILD_DIR")) / "parity_gen"
out_dir.mkdir(parents=True, exist_ok=True)


def literal(text):
    body = text.replace("\\", "\\\\").replace('"', '\\"')
    return "\n".join('    "%s\\n"' % line for line in body.splitlines())


lines = ["#pragma once", "// Generated by tools/embed_parity_traces.py from sim/traces.",
         "struct ParityTrace { const char* name; const char* text; };",
         "static const ParityTrace kParityTraces[] = {"]
for name in TRACES:
    text = (project / "sim" / "traces" / (name + ".trace")).read_text(encoding="utf-8")
    lines.append('  {"%s",\n%s},' % (name, literal(text)))
lines += ["};", ""]
header = out_dir / "parity_traces.h"
content = "\n".join(lines)
if not header.exists() or header.read_text(encoding="utf-8") != content:
    header.write_text(content, encoding="utf-8")
env.Append(CPPPATH=[str(out_dir)])
