#!/usr/bin/env python3
"""Regenerate the static TFT_eSPI RGB565 scene from the owner-provided concept.

Requires existing Pillow. No dithering/interpolation, crop, or byte-swapped literals.
Paths default relative to firmware root, independent of working directory.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]

def convert(source, width, height):
    with Image.open(source) as image:
        original = ImageOps.exif_transpose(image).convert("RGBA")
    # Uniform contain scale; integer dimensions round by at most half a pixel.
    scale = min(width / original.width, height / original.height)
    fitted = original.resize((max(1, round(original.width * scale)),
                              max(1, round(original.height * scale))), Image.Resampling.NEAREST)
    canvas = Image.new("RGBA", (width, height), (250, 247, 235, 255))
    position = ((width - fitted.width) // 2, (height - fitted.height) // 2)
    canvas.alpha_composite(fitted, position)
    rgb = canvas.convert("RGB")
    pixels = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in rgb.getdata()]
    # Preview the quantized values rather than the unquantized original.
    preview = Image.new("RGB", (width, height))
    preview.putdata([(((v >> 11) & 31) * 255 // 31,
                      ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31) for v in pixels])
    return pixels, preview, {"source_size": list(original.size), "scale": scale,
                            "resized_size": list(fitted.size), "offset": list(position), "crop": False}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "assets/source/xuna_and_bg.png")
    parser.add_argument("--width", type=int, default=320)
    parser.add_argument("--height", type=int, default=170)
    args = parser.parse_args()
    if args.width <= 0 or args.height <= 0:
        parser.error("width and height must be positive")
    pixels, preview, metadata = convert(args.source, args.width, args.height)
    header = ROOT / "include/assets/XunaScene.h"
    cpp = ROOT / "src/assets/XunaScene.cpp"
    generated = ROOT / "assets/generated"
    for folder in (header.parent, cpp.parent, generated):
        folder.mkdir(parents=True, exist_ok=True)
    header.write_text("""// Generated by tools/convert_scene.py; do not edit pixels manually.
#pragma once
#include <cstdint>
namespace xuna { namespace scene {
constexpr uint16_t kWidth = %d;
constexpr uint16_t kHeight = %d;
extern const uint16_t kPixels[kWidth * kHeight];
}}
""" % (args.width, args.height))
    rows = ["  " + ", ".join("0x%04x" % v for v in pixels[i:i+12]) + ","
            for i in range(0, len(pixels), 12)]
    cpp.write_text("""// Generated by tools/convert_scene.py; canonical RGB565 words, R5:G6:B5.
#include <pgmspace.h>
#include "assets/XunaScene.h"
namespace xuna { namespace scene {
alignas(4) const uint16_t kPixels[kWidth * kHeight] PROGMEM = {
""" + "\n".join(rows) + "\n};\n}}\n")
    preview.save(generated / "xuna_scene_rgb565.png")
    metadata.update({"source_sha256": hashlib.sha256(args.source.read_bytes()).hexdigest(),
                     "target_size": [args.width, args.height], "pixel_bytes": len(pixels)*2,
                     "format": "RGB565 canonical words; TFT_eSPI setSwapBytes(true)",
                     "resampling": "nearest-neighbor"})
    (generated / "xuna_scene.json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(json.dumps(metadata, indent=2))

if __name__ == "__main__":
    main()
